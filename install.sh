#!/bin/bash
# install.sh — 在网关机（单台 Linux 主机，以本仓库实测环境 J1900/Ubuntu 26.04 为例）上以 root 执行的一键安装
# 用法: 把整个目录放到 /opt/route-gw-deploy 下，然后 bash /opt/route-gw-deploy/install.sh
set -euo pipefail

BASE="$(cd "$(dirname "$0")" && pwd)"
FILES="$BASE/files"
export DEBIAN_FRONTEND=noninteractive

echo "[1/8] 安装软件包"
# 等待可能残留的 apt/dpkg 锁（首次开机模板初始化常见），最多 5 分钟
for i in $(seq 1 60); do
    fuser /var/lib/dpkg/lock-frontend >/dev/null 2>&1 || break
    echo "  dpkg 锁被占用，等待... ($i/60)"; sleep 5
done
DEBIAN_FRONTEND=noninteractive dpkg --configure -a || true
apt-get update -qq
apt-get install -y -qq wireguard-tools dnsmasq curl ca-certificates cron iptables iproute2

echo "[2/8] 投放配置文件"
install -d -m 700 /etc/wireguard
install -d /usr/local/bin /etc/dnsmasq.d /etc/cron.d /etc/sysctl.d
# 防 CRLF 残留（从 Windows 侧打包时可能出现）
for f in "$FILES"/usr/local/bin/*.sh "$FILES"/etc/wireguard/wg0.conf; do sed -i 's/\r$//' "$f"; done

# wg0.conf 是唯一带真实密钥的文件：升级时绝不覆盖已有配置，否则会把在用的私钥冲掉。
# 首次安装（文件不存在）才投放示例；确需重置用 FORCE_WG_CONF=1。
if [ ! -f /etc/wireguard/wg0.conf ] || [ "${FORCE_WG_CONF:-0}" = "1" ]; then
    install -m 600 "$FILES/etc/wireguard/wg0.conf" /etc/wireguard/wg0.conf
    echo "  已投放 wg0.conf（示例值，请确认 PrivateKey/PublicKey/Endpoint）"
else
    echo "  保留已有 /etc/wireguard/wg0.conf（真实密钥不覆盖）"
fi

install -m 755 "$FILES"/usr/local/bin/*.sh /usr/local/bin/
# overlay NAT（ZeroTier/Tailscale）单元只安装，不自动 enable：
# 装好 overlay 后再 systemctl enable --now route-gw-overlay
install -m 644 "$FILES/etc/systemd/system/route-gw-overlay.service" /etc/systemd/system/route-gw-overlay.service
# DNS 自愈：dnsmasq 挂了全内网 DNS 就静默中断（2026-11-05 事故），必须有人定期检查
install -m 644 "$FILES/etc/systemd/system/dnsmasq-healthcheck.service" /etc/systemd/system/dnsmasq-healthcheck.service
install -m 644 "$FILES/etc/systemd/system/dnsmasq-healthcheck.timer" /etc/systemd/system/dnsmasq-healthcheck.timer
install -m 644 "$FILES/etc/dnsmasq.conf" /etc/dnsmasq.conf
install -m 644 "$FILES/etc/dnsmasq.d/00-listen.conf" /etc/dnsmasq.d/00-listen.conf

# 手工补充域名是用户自己的配置：已存在就保留，避免升级时被包里的占位值覆盖
if [ ! -f /etc/dnsmasq.d/98-custom-domain.conf ]; then
    install -m 644 "$FILES/etc/dnsmasq.d/98-custom-domain.conf" /etc/dnsmasq.d/98-custom-domain.conf
fi

# 隧道内 DNS 上游走本机覆盖文件，仓库里只保留文档占位值
if [ -n "${GW_GFW_DNS:-}" ]; then
    install -d /etc/default
    touch /etc/default/route-gw
    if grep -q '^GW_GFW_DNS=' /etc/default/route-gw; then
        sed -i "s|^GW_GFW_DNS=.*|GW_GFW_DNS=$GW_GFW_DNS|" /etc/default/route-gw
    else
        printf 'GW_GFW_DNS=%s\n' "$GW_GFW_DNS" >> /etc/default/route-gw
    fi
    chmod 644 /etc/default/route-gw
    # 只在仍是占位值时替换，别动用户自己加的真实 DNS
    sed -i "s|198\.51\.100\.53|$GW_GFW_DNS|g" /etc/dnsmasq.d/98-custom-domain.conf
fi
install -m 644 "$FILES/etc/cron.d/route-lists" /etc/cron.d/
install -m 644 "$FILES/etc/sysctl.d/99-route-gw.conf" /etc/sysctl.d/

# Ubuntu 26.04+ 自带 wg-quick AppArmor 策略，默认拒绝 PostUp/PostDown 执行自定义脚本。
# 只把两个 route-gw 钩子加入 local override（不动 wg-quick 自身的其它限制）。
if [ -f /etc/apparmor.d/wg-quick ]; then
    install -d /etc/apparmor.d/local
    touch /etc/apparmor.d/local/wg-quick
    for line in "/usr/local/bin/wg-route-up.sh rux," "/usr/local/bin/wg-route-down.sh rux,"; do
        grep -qxF "$line" /etc/apparmor.d/local/wg-quick 2>/dev/null || \
            printf '%s\n' "$line" >> /etc/apparmor.d/local/wg-quick
    done
    command -v apparmor_parser >/dev/null 2>&1 && \
        apparmor_parser -r /etc/apparmor.d/wg-quick 2>/dev/null || true
    echo "  已放行 wg-quick 的 route-gw PostUp/PostDown 钩子 (AppArmor local override)"
fi

echo "[3/8] systemd 依赖顺序"
# 防御: ubuntu-fan（docker.io 的 Recommends）会投放 /etc/dnsmasq.d/ubuntu-fan，
# 其中的 bind-interfaces 与本项目 /etc/dnsmasq.conf 的 bind-dynamic 互斥，
# 会让 dnsmasq 在下次重启时直接启动失败（2026-11-05 事故）。只注释冲突行，保留 except-interface=fan-*。
if [ -f /etc/dnsmasq.d/ubuntu-fan ] && grep -qE '^[[:space:]]*bind-interfaces[[:space:]]*$' /etc/dnsmasq.d/ubuntu-fan; then
    sed -i 's|^[[:space:]]*bind-interfaces[[:space:]]*$|# bind-interfaces   # 与本项目 bind-dynamic 互斥, install.sh 自动注释|' /etc/dnsmasq.d/ubuntu-fan
    echo "  已注释 /etc/dnsmasq.d/ubuntu-fan 里的 bind-interfaces（与 bind-dynamic 冲突）"
fi
install -d /etc/systemd/system/dnsmasq.service.d
install -m 644 "$FILES/etc/systemd/system/dnsmasq.service.d/override.conf" /etc/systemd/system/dnsmasq.service.d/
systemctl daemon-reload
sysctl --system >/dev/null 2>&1 || true

# DNS 监听网卡跟随默认路由（单臂旁路由 = LAN/WAN 同网卡），不写死接口名
LAN_IF=$(ip route show default 2>/dev/null | awk '/^default/{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
[ -z "$LAN_IF" ] && LAN_IF=enp3s0
cat > /etc/dnsmasq.d/00-listen.conf <<EOF
# generated by install.sh — 跟随默认路由网卡，勿手改
interface=lo
interface=$LAN_IF
EOF
chmod 644 /etc/dnsmasq.d/00-listen.conf

echo "[4/8] 接管 DNS: 停用 systemd-resolved，resolv.conf 指向本机 dnsmasq"
systemctl disable --now systemd-resolved 2>/dev/null || true
rm -f /etc/resolv.conf
printf 'nameserver 127.0.0.1\n' > /etc/resolv.conf
# 注意: 若本机是 PVE 等虚拟化平台的容器，平台侧 hook 可能在重启时重写 resolv.conf，
# 那种情况要在平台侧把 nameserver 也设成本机（本项目当前部署为原生单机，无此问题）。

echo "[5/8] 拉起 WireGuard 隧道"
systemctl enable --now wg-quick@wg0
# 升级场景下隧道本来就在跑，enable --now 不会重跑 PostUp；显式再执行一次，
# 让新的 LAN 网段/NAT 规则立即生效（脚本本身幂等）。
/usr/local/bin/wg-route-up.sh || true

echo "[6/8] 首次拉取数据源（github 走隧道下载）"
/usr/local/bin/update-lists.sh || echo "WARN: 首次更新失败，隧道恢复后手动执行 /usr/local/bin/update-lists.sh"

echo "[7/8] 启动 dnsmasq 与 cron"
systemctl enable --now dnsmasq cron
systemctl enable --now dnsmasq-healthcheck.timer
# 已装 ZeroTier/Tailscale 的机器可启用 overlay NAT；没有 overlay 的机器保持不启动
if command -v zerotier-cli >/dev/null 2>&1 || command -v tailscale >/dev/null 2>&1; then
    systemctl enable --now route-gw-overlay.service 2>/dev/null || true
    echo "  已启用 route-gw-overlay.service（LAN -> ZeroTier/Tailscale NAT）"
else
    echo "  未检测到 ZeroTier/Tailscale；装好后执行 systemctl enable --now route-gw-overlay"
fi
systemctl restart dnsmasq

# 可选：ZT_NETWORK_ID=... 时自动安装/加入 ZeroTier 并启用 overlay NAT。
# 网络 ID 只从环境变量传，不写进仓库。
if [ -n "${ZT_NETWORK_ID:-}" ] && [ -f "$BASE/install-zerotier.sh" ]; then
    echo "[7b] 安装/加入 ZeroTier 并启用 overlay NAT"
    bash "$BASE/install-zerotier.sh" "$ZT_NETWORK_ID" || echo "WARN: ZeroTier 安装/加入失败，稍后手动处理"
fi

echo "[8/8] 状态快照"
sleep 2
echo "--- wg ---";      wg show wg0 | head -4 || true
echo "--- rule ---";    ip rule show | grep -E '32764|32765' || echo "MISSING RULES"
echo "--- table ---";   ip route show table 51820 || true
echo "--- china ---";   wc -l /etc/china_ip_list.txt 2>/dev/null || echo "MISSING LIST"
echo "--- gfw ---";     grep -c '^server=' /etc/dnsmasq.d/99-gfw.conf 2>/dev/null || echo "MISSING GFW"
echo "--- lan ---";     ip route show default; ip -4 -br addr show dev "$LAN_IF"
echo "--- nat ---";     iptables -t nat -S ROUTE_GW_NAT 2>/dev/null || echo "MISSING NAT"
echo "--- svc ---";     systemctl is-active wg-quick@wg0 dnsmasq cron dnsmasq-healthcheck.timer
echo "DONE"
echo "同网段客户端把「默认网关 + DNS」都指向本机 $LAN_IF 的地址即可分流。"
